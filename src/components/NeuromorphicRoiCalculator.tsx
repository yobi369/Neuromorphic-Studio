import { useState } from "react";
import {
  BatteryCharging,
  DollarSign,
  TrendingUp,
  Leaf,
  Clock,
  Cpu,
  Layers,
  Sparkles,
  Download,
  Copy,
  Check,
  Info,
  Zap,
} from "lucide-react";

export function NeuromorphicRoiCalculator() {
  // Deployment inputs
  const [fleetSize, setFleetSize] = useState<number>(5000); // 5,000 edge IoT / drone units
  const [batteryCapacityMah, setBatteryCapacityMah] = useState<number>(1200); // 1200 mAh Li-Ion
  const [batteryVoltage] = useState<number>(3.7); // 3.7V nominal
  const [sparsityPercent, setSparsityPercent] = useState<number>(94); // 94% idle/sparse
  const [batterySwapLaborCost, setBatterySwapLaborCost] = useState<number>(45); // $45 per field technician swap
  const [batteryCellCost, setBatteryCellCost] = useState<number>(6.5); // $6.50 per replacement cell
  const [mcuActivePowerMw, setMcuActivePowerMw] = useState<number>(140); // 140 mW active
  const [mcuIdlePowerMw, setMcuIdlePowerMw] = useState<number>(28); // 28 mW idle polling
  const [snnActivePowerMw, setSnnActivePowerMw] = useState<number>(3.8); // 3.8 mW active
  const [snnIdlePowerMw, setSnnIdlePowerMw] = useState<number>(0.04); // 40 µW event standby

  const [copiedSummary, setCopiedSummary] = useState(false);

  // Battery Energy in Watt-hours (Wh) = (mAh * V) / 1000
  const batteryWh = (batteryCapacityMah * batteryVoltage) / 1000;

  // Average Power Consumption (mW)
  // Avg Power = (ActiveTime% * ActivePower) + (IdleTime% * IdlePower)
  const activeFraction = (100 - sparsityPercent) / 100;
  const idleFraction = sparsityPercent / 100;

  const mcuAvgPowerMw = activeFraction * mcuActivePowerMw + idleFraction * mcuIdlePowerMw;
  const snnAvgPowerMw = activeFraction * snnActivePowerMw + idleFraction * snnIdlePowerMw;

  // Battery life in hours = (Battery Wh * 1000) / Avg Power (mW)
  const mcuBatteryHours = (batteryWh * 1000) / mcuAvgPowerMw;
  const snnBatteryHours = (batteryWh * 1000) / snnAvgPowerMw;

  const mcuBatteryDays = mcuBatteryHours / 24;
  const snnBatteryDays = snnBatteryHours / 24;

  const mcuBatteryYears = mcuBatteryDays / 365.25;
  const snnBatteryYears = snnBatteryDays / 365.25;

  // 5-Year Horizon Analysis
  const horizonYears = 5;
  const horizonDays = horizonYears * 365.25;

  // Swaps needed per device over 5 years
  const mcuSwapsPerDevice = Math.max(0, Math.floor(horizonDays / mcuBatteryDays));
  const snnSwapsPerDevice = Math.max(0, Math.floor(horizonDays / snnBatteryDays));

  // Replacement cost per swap
  const costPerSwap = batteryCellCost + batterySwapLaborCost;

  // Total 5-year battery maintenance cost for the whole fleet
  const mcuTotalFleetCost = fleetSize * mcuSwapsPerDevice * costPerSwap;
  const snnTotalFleetCost = fleetSize * snnSwapsPerDevice * costPerSwap;
  const totalFleetSavings = mcuTotalFleetCost - snnTotalFleetCost;

  // Energy Saved (kWh) over 5 years
  const mcuTotalKwh = (fleetSize * mcuAvgPowerMw * 24 * horizonDays) / (1000 * 1000);
  const snnTotalKwh = (fleetSize * snnAvgPowerMw * 24 * horizonDays) / (1000 * 1000);
  const totalKwhSaved = Math.max(0, mcuTotalKwh - snnTotalKwh);

  // Illustrative carbon factor (0.386 kg CO2e/kWh); replace with a current location-specific source
  const co2AvoidedKg = totalKwhSaved * 0.386;

  const copyExecutiveSummary = () => {
    const text = `===============================================================
EXECUTIVE ROI & BATTERY LIFE ANALYSIS: NEUROMORPHIC VS CONVENTIONAL
Generated by Neuromorphic Studio research prototype — scenario only
===============================================================
Deployment Profile:
• Fleet Size: ${fleetSize.toLocaleString()} Edge IoT/Sensor Nodes
• Battery Spec: ${batteryCapacityMah} mAh Li-ion (${batteryWh.toFixed(2)} Wh)
• Temporal Event Sparsity: ${sparsityPercent}%
• Replacement Cost per Unit: $${costPerSwap.toFixed(2)} ($${batteryCellCost} cell + $${batterySwapLaborCost} labor)

Battery Longevity:
• Conventional Embedded MCU/Edge GPU: ${mcuBatteryDays >= 30 ? (mcuBatteryDays / 30.4).toFixed(1) + " months" : mcuBatteryDays.toFixed(1) + " days"} (${mcuAvgPowerMw.toFixed(1)} mW avg)
• Neuromorphic Event SNN: ${snnBatteryYears >= 1.0 ? snnBatteryYears.toFixed(2) + " years" : snnBatteryDays.toFixed(0) + " days"} (${snnAvgPowerMw.toFixed(2)} mW avg)
• Longevity Multiplier: ${(snnBatteryHours / mcuBatteryHours).toFixed(1)}x longer operation

5-Year Financial & Operational TCO:
• Conventional Battery Maintenance Cost: $${mcuTotalFleetCost.toLocaleString()} (${mcuSwapsPerDevice} replacements/device)
• Neuromorphic Battery Maintenance Cost: $${snnTotalFleetCost.toLocaleString()} (${snnSwapsPerDevice} replacements/device)
• Total Capital & OpEx Savings: $${totalFleetSavings.toLocaleString()}
• Total Electrical Energy Saved: ${totalKwhSaved.toFixed(0)} kWh
• Carbon Footprint Avoided: ${(co2AvoidedKg / 1000).toFixed(2)} Metric Tonnes CO2e
===============================================================`;
    navigator.clipboard.writeText(text);
    setCopiedSummary(true);
    setTimeout(() => setCopiedSummary(false), 2500);
  };

  return (
    <div className="space-y-6">
      {/* Header Banner */}
      <div className="p-6 rounded-2xl border border-cyan-500/30 bg-gradient-to-r from-slate-900 via-cyan-950/40 to-slate-900 shadow-xl flex flex-col md:flex-row items-start md:items-center justify-between gap-4">
        <div className="space-y-1">
          <div className="flex items-center gap-2">
            <span className="px-2 py-0.5 rounded text-[10px] font-mono font-bold bg-cyan-500/20 text-cyan-300 border border-cyan-500/40">
              ASSUMPTION-BASED SCENARIO
            </span>
            <span className="text-xs text-emerald-400 font-mono font-semibold">
              User-defined power scenario calculator
            </span>
          </div>
          <h2 className="text-xl font-bold text-white flex items-center gap-2">
            <BatteryCharging className="w-5 h-5 text-cyan-400" />
            <span>Neuromorphic Battery Longevity &amp; Fleet ROI Calculator</span>
          </h2>
          <p className="text-xs text-slate-400 max-w-2xl leading-relaxed">
            Illustrative arithmetic only. Default values are placeholders, not vendor specifications or measurements. Replace every input with a sourced or measured value before using the result in a proposal or publication.
          </p>
        </div>

        <button
          onClick={copyExecutiveSummary}
          className="px-4 py-2.5 rounded-xl bg-cyan-500/20 hover:bg-cyan-500/30 text-cyan-300 border border-cyan-500/40 font-mono text-xs font-bold transition-all flex items-center gap-2 cursor-pointer shrink-0"
        >
          {copiedSummary ? (
            <>
              <Check className="w-4 h-4 text-emerald-400" />
              <span>Summary Copied!</span>
            </>
          ) : (
            <>
              <Copy className="w-4 h-4" />
              <span>Copy Scenario Summary</span>
            </>
          )}
        </button>
      </div>

      <div className="rounded-lg border border-amber-700/40 bg-amber-950/20 p-3 text-xs text-amber-200">
        Scenario outputs are not evidence that an SNN accelerator uses less energy than an MCU. Battery life assumes constant average load and ideal battery capacity; it excludes conversion losses, temperature, aging, workload variance and device-specific constraints. The carbon factor is illustrative and must be replaced with a location-specific source.
      </div>

      {/* Main Grid: Inputs vs Impact Metrics */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Left Column: Interactive Parametric Controls */}
        <div className="lg:col-span-5 space-y-4">
          <div className="p-5 rounded-2xl border border-slate-800 bg-slate-900/70 space-y-4">
            <div className="flex items-center justify-between border-b border-slate-800 pb-3">
              <h3 className="text-sm font-bold text-slate-200 flex items-center gap-2">
                <Cpu className="w-4 h-4 text-cyan-400" />
                <span>Deployment &amp; Fleet Parameters</span>
              </h3>
              <span className="text-[10px] font-mono text-slate-500">Live Simulation</span>
            </div>

            {/* Fleet Size */}
            <div className="space-y-1.5">
              <div className="flex justify-between text-xs font-mono text-slate-300">
                <span>Fleet Size (Edge Nodes):</span>
                <span className="text-cyan-400 font-bold">{fleetSize.toLocaleString()} units</span>
              </div>
              <input
                type="range"
                min="100"
                max="50000"
                step="100"
                value={fleetSize}
                onChange={(e) => setFleetSize(Number(e.target.value))}
                className="w-full h-1.5 bg-slate-800 rounded-lg appearance-none cursor-pointer accent-cyan-400"
              />
              <div className="flex justify-between text-[10px] text-slate-500 font-mono">
                <span>100 units</span>
                <span>50,000 units</span>
              </div>
            </div>

            {/* Battery Capacity */}
            <div className="space-y-1.5">
              <div className="flex justify-between text-xs font-mono text-slate-300">
                <span>Battery Capacity:</span>
                <span className="text-cyan-400 font-bold">
                  {batteryCapacityMah} mAh ({batteryWh.toFixed(1)} Wh)
                </span>
              </div>
              <input
                type="range"
                min="200"
                max="5000"
                step="100"
                value={batteryCapacityMah}
                onChange={(e) => setBatteryCapacityMah(Number(e.target.value))}
                className="w-full h-1.5 bg-slate-800 rounded-lg appearance-none cursor-pointer accent-cyan-400"
              />
              <div className="flex justify-between text-[10px] text-slate-500 font-mono">
                <span>Coin Cell (200 mAh)</span>
                <span>Li-Po (5000 mAh)</span>
              </div>
            </div>

            {/* Event Sparsity */}
            <div className="space-y-1.5">
              <div className="flex justify-between text-xs font-mono text-slate-300">
                <span>Temporal Event Sparsity:</span>
                <span className="text-emerald-400 font-bold">{sparsityPercent}% idle</span>
              </div>
              <input
                type="range"
                min="50"
                max="99"
                step="1"
                value={sparsityPercent}
                onChange={(e) => setSparsityPercent(Number(e.target.value))}
                className="w-full h-1.5 bg-slate-800 rounded-lg appearance-none cursor-pointer accent-emerald-400"
              />
              <p className="text-[10px] text-slate-500 leading-tight">
                Percentage of time the scene has zero motion/sound where neuromorphic silicon enters microsecond sub-microwatt sleep.
              </p>
            </div>

            {/* Maintenance Costs */}
            <div className="grid grid-cols-2 gap-3 pt-2 border-t border-slate-800">
              <div className="space-y-1">
                <label className="text-[11px] text-slate-400 font-mono">Replacement Cell:</label>
                <div className="relative">
                  <span className="absolute left-2.5 top-2 text-xs text-slate-500">$</span>
                  <input
                    type="number"
                    value={batteryCellCost}
                    onChange={(e) => setBatteryCellCost(Math.max(1, Number(e.target.value)))}
                    className="w-full pl-6 pr-2 py-1.5 rounded-lg bg-slate-950 border border-slate-800 text-xs text-slate-200 font-mono"
                  />
                </div>
              </div>
              <div className="space-y-1">
                <label className="text-[11px] text-slate-400 font-mono">Field Dispatch Labor:</label>
                <div className="relative">
                  <span className="absolute left-2.5 top-2 text-xs text-slate-500">$</span>
                  <input
                    type="number"
                    value={batterySwapLaborCost}
                    onChange={(e) => setBatterySwapLaborCost(Math.max(0, Number(e.target.value)))}
                    className="w-full pl-6 pr-2 py-1.5 rounded-lg bg-slate-950 border border-slate-800 text-xs text-slate-200 font-mono"
                  />
                </div>
              </div>
            </div>

            {/* Hardware Power Specs Accordion */}
            <div className="p-3 rounded-xl bg-slate-950 border border-slate-800 space-y-2 text-xs font-mono">
              <div className="text-[11px] font-bold text-slate-300 flex items-center gap-1.5">
                <Zap className="w-3.5 h-3.5 text-cyan-400" />
                <span>Silicon Power Consumption Model</span>
              </div>
              <div className="grid grid-cols-2 gap-2 text-[10px]">
                <div className="p-2 rounded bg-slate-900 border border-slate-800">
                  <div className="text-slate-400">Conventional MCU</div>
                  <div className="text-slate-200 mt-1">Active: {mcuActivePowerMw} mW</div>
                  <div className="text-slate-500">Standby: {mcuIdlePowerMw} mW</div>
                  <div className="text-amber-400 font-bold mt-1">Avg: {mcuAvgPowerMw.toFixed(1)} mW</div>
                </div>
                <div className="p-2 rounded bg-cyan-950/40 border border-cyan-800/60">
                  <div className="text-cyan-300">Neuromorphic SNN</div>
                  <div className="text-slate-200 mt-1">Active: {snnActivePowerMw} mW</div>
                  <div className="text-slate-500">Standby: {snnIdlePowerMw} mW</div>
                  <div className="text-emerald-400 font-bold mt-1">Avg: {snnAvgPowerMw.toFixed(2)} mW</div>
                </div>
              </div>
            </div>
          </div>
        </div>

        {/* Right Column: Longevity Comparison & 5-Year TCO Outcomes */}
        <div className="lg:col-span-7 space-y-4">
          {/* Main Longevity Card */}
          <div className="p-6 rounded-2xl border border-cyan-500/40 bg-gradient-to-br from-slate-900 via-slate-900 to-cyan-950/40 shadow-xl space-y-5">
            <div className="flex items-center justify-between">
              <span className="text-xs font-mono text-cyan-300 font-semibold uppercase flex items-center gap-1.5">
                <Clock className="w-4 h-4 text-cyan-400" />
                Single Battery Charge Endurance
              </span>
              <span className="px-2.5 py-0.5 rounded-full text-xs font-mono font-bold bg-emerald-500/20 text-emerald-400 border border-emerald-500/40">
                {(snnBatteryHours / mcuBatteryHours).toFixed(1)}x Longer Lifespan
              </span>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              {/* Conventional MCU */}
              <div className="p-4 rounded-xl bg-slate-950/80 border border-slate-800 space-y-2">
                <div className="text-[11px] font-mono text-slate-400 flex items-center justify-between">
                  <span>Standard MCU / GPU</span>
                  <span className="text-amber-400 font-bold">Continuous Clock</span>
                </div>
                <div className="text-2xl font-black text-slate-200 font-mono">
                  {mcuBatteryDays >= 30
                    ? `${(mcuBatteryDays / 30.4).toFixed(1)} months`
                    : `${mcuBatteryDays.toFixed(1)} days`}
                </div>
                <p className="text-[11px] text-slate-400">
                  {mcuSwapsPerDevice} battery swaps needed over 5 years. High continuous sampling drain.
                </p>
                <div className="w-full bg-slate-800 h-2 rounded-full overflow-hidden">
                  <div
                    className="bg-amber-400 h-full rounded-full"
                    style={{ width: `${Math.min(100, (mcuBatteryDays / (snnBatteryDays || 1)) * 100)}%` }}
                  />
                </div>
              </div>

              {/* Neuromorphic SNN */}
              <div className="p-4 rounded-xl bg-cyan-950/60 border border-cyan-500/50 space-y-2 shadow-lg shadow-cyan-950/30">
                <div className="text-[11px] font-mono text-cyan-300 flex items-center justify-between">
                  <span>Neuromorphic SNN</span>
                  <span className="text-emerald-400 font-bold">Event-Driven Sleep</span>
                </div>
                <div className="text-2xl font-black text-emerald-400 font-mono">
                  {snnBatteryYears >= 1.0
                    ? `${snnBatteryYears.toFixed(2)} years`
                    : `${snnBatteryDays.toFixed(0)} days`}
                </div>
                <p className="text-[11px] text-cyan-200/80">
                  {snnSwapsPerDevice === 0 ? "Zero battery swaps needed!" : `${snnSwapsPerDevice} swap over 5 years.`} True sub-milliwatt edge endurance.
                </p>
                <div className="w-full bg-slate-800 h-2 rounded-full overflow-hidden">
                  <div className="bg-gradient-to-r from-cyan-400 to-emerald-400 h-full rounded-full w-full" />
                </div>
              </div>
            </div>

            {/* 5-Year TCO Cost Comparison */}
            <div className="pt-4 border-t border-slate-800 space-y-3">
              <div className="flex items-center justify-between text-xs font-mono">
                <span className="text-slate-300 font-bold">5-Year Fleet Battery Maintenance Cost:</span>
                <span className="text-emerald-400 font-extrabold text-sm">
                  Save ${totalFleetSavings.toLocaleString()}
                </span>
              </div>

              <div className="space-y-2">
                <div>
                  <div className="flex justify-between text-[11px] font-mono mb-1">
                    <span className="text-slate-400">Standard Fleet ({fleetSize.toLocaleString()} devices):</span>
                    <span className="text-red-400 font-bold">${mcuTotalFleetCost.toLocaleString()}</span>
                  </div>
                  <div className="w-full bg-slate-800 h-2.5 rounded-full overflow-hidden">
                    <div className="bg-red-500/80 h-full rounded-full w-full" />
                  </div>
                </div>

                <div>
                  <div className="flex justify-between text-[11px] font-mono mb-1">
                    <span className="text-slate-400">Neuromorphic Fleet:</span>
                    <span className="text-emerald-400 font-bold">${snnTotalFleetCost.toLocaleString()}</span>
                  </div>
                  <div className="w-full bg-slate-800 h-2.5 rounded-full overflow-hidden">
                    <div
                      className="bg-emerald-400 h-full rounded-full transition-all"
                      style={{
                        width: `${Math.max(2, Math.min(100, (snnTotalFleetCost / (mcuTotalFleetCost || 1)) * 100))}%`,
                      }}
                    />
                  </div>
                </div>
              </div>
            </div>
          </div>

          {/* Environmental & ESG Metrics */}
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
            <div className="p-4 rounded-xl border border-slate-800 bg-slate-900/80 space-y-1">
              <div className="flex items-center gap-1.5 text-xs font-mono text-emerald-400">
                <DollarSign className="w-4 h-4" />
                <span>OpEx Reduction</span>
              </div>
              <div className="text-xl font-extrabold text-white font-mono">
                {mcuTotalFleetCost > 0
                  ? `${Math.round((totalFleetSavings / mcuTotalFleetCost) * 100)}%`
                  : "0%"}
              </div>
              <p className="text-[10px] text-slate-500">Fleet maintenance labor eliminated</p>
            </div>

            <div className="p-4 rounded-xl border border-slate-800 bg-slate-900/80 space-y-1">
              <div className="flex items-center gap-1.5 text-xs font-mono text-cyan-400">
                <Zap className="w-4 h-4" />
                <span>Electricity Saved</span>
              </div>
              <div className="text-xl font-extrabold text-white font-mono">
                {totalKwhSaved > 1000
                  ? `${(totalKwhSaved / 1000).toFixed(1)} MWh`
                  : `${totalKwhSaved.toFixed(0)} kWh`}
              </div>
              <p className="text-[10px] text-slate-500">Over 5 years across {fleetSize.toLocaleString()} units</p>
            </div>

            <div className="p-4 rounded-xl border border-slate-800 bg-slate-900/80 space-y-1">
              <div className="flex items-center gap-1.5 text-xs font-mono text-teal-300">
                <Leaf className="w-4 h-4" />
                <span>CO₂e Avoided</span>
              </div>
              <div className="text-xl font-extrabold text-white font-mono">
                {(co2AvoidedKg / 1000).toFixed(2)} <span className="text-xs font-normal">tonnes</span>
              </div>
              <p className="text-[10px] text-slate-500">Equivalent to EPA grid factor</p>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
